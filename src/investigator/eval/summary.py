"""Turning a sweep's runs into scores and a comparison table.

The output depends only on the files the sweep left behind, so it can be regenerated
exactly, and the numbers in the docs can always be traced to raw results.
"""

import json
from collections.abc import Sequence
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from statistics import fmean, median

from investigator.domain.causes import Outcome
from investigator.domain.report import Report
from investigator.domain.telemetry import LogRecord
from investigator.eval.ground_truth import Tag, load_ground_truth
from investigator.eval.runner import RECORD_FILE, REPORT_FILE, TRACE_FILE, RunRecord
from investigator.eval.scoring import RunScore, score_run
from investigator.systems import System
from investigator.world.dataset import Dataset

SYSTEM_NAMES = {System.MULTI: "Agent team", System.SINGLE: "Single agent"}


@dataclass(frozen=True)
class SweepResults:
    scores: tuple[RunScore, ...]
    records: tuple[RunRecord, ...]
    """Every run, including ones that crashed and have no score."""

    @property
    def systems(self) -> list[System]:
        return [s for s in System if any(score.system == s for score in self.scores)]

    def of(self, system: System) -> list[RunScore]:
        return [s for s in self.scores if s.system == system]


def load_results(sweep: Path, dataset: Dataset) -> SweepResults:
    @cache
    def logs(incident_id: str) -> dict[str, LogRecord]:
        return {record.id: record for record in dataset.telemetry(incident_id).logs}

    scores, records = [], []
    for run_dir in sorted(p for p in sweep.iterdir() if (p / RECORD_FILE).exists()):
        record = RunRecord.model_validate_json((run_dir / RECORD_FILE).read_text())
        records.append(record)
        if record.error is not None:
            continue
        report = Report.model_validate_json((run_dir / REPORT_FILE).read_text())
        trace = [json.loads(line) for line in (run_dir / TRACE_FILE).read_text().splitlines()]
        truth = load_ground_truth(dataset, record.incident_id)
        scores.append(score_run(record, report, trace, truth, logs(record.incident_id)))
    return SweepResults(tuple(scores), tuple(records))


def write_scores(results: SweepResults, path: Path) -> None:
    path.write_text(
        json.dumps([score.model_dump(mode="json") for score in results.scores], indent=1) + "\n"
    )


def render_summary(results: SweepResults, title: str) -> str:
    systems = results.systems
    names = [SYSTEM_NAMES[s] for s in systems]
    lines = [
        f"# {title}",
        "",
        "Generated by `investigator eval report` from the runs in this directory. Do not edit;",
        "regenerate it instead.",
        "",
        *(f"- {line}" for line in setup_lines(results)),
        "",
        "## Overall",
        "",
        _header("", names),
        *(_row(label, cells) for label, cells in overall_rows(results)),
        "",
        "## By incident",
        "",
        "Correct runs out of trials, then each run's outcome and whether it was right.",
        "",
        _header("Incident", names),
        *_incident_rows(results, systems),
        "",
        "## By tag",
        "",
        "Correct runs out of all runs on incidents with that tag.",
        "",
        _header("Tag", names),
        *(_row(tag.value, [_tag_cell(results.of(s), tag) for s in systems]) for tag in Tag),
    ]
    if crashed := [r for r in results.records if r.error is not None]:
        lines += ["", "## Runs that crashed", ""]
        lines += [f"- {r.incident_id} {r.system} trial {r.trial}: {r.error}" for r in crashed]
    return "\n".join(lines) + "\n"


def setup_lines(results: SweepResults) -> list[str]:
    """What was run, and with what."""
    records = results.records
    incidents = sorted({r.incident_id for r in records})
    trials = max((r.trial for r in records), default=0)
    models = sorted({r.model for r in records})
    digests = sorted({r.config_digest for r in records})
    started = min(r.started_at for r in records) if records else None
    return [
        f"Incidents: {len(incidents)} ({', '.join(incidents)})",
        f"Trials per incident and system: {trials}",
        f"Model: {', '.join(models)}",
        f"Configuration and prompt digest: {', '.join(digests)}"
        + (" (more than one: runs used different settings)" if len(digests) > 1 else ""),
        f"First run started: {started:%Y-%m-%d %H:%M} UTC" if started else "No runs",
    ]


def overall_rows(results: SweepResults) -> list[tuple[str, list[str]]]:
    """Each headline measure, with one cell per system."""
    per_system = [_overall_cells(results.of(s)) for s in results.systems]
    labels = list(per_system[0]) if per_system else []
    return [(label, [cells[label] for cells in per_system]) for label in labels]


def _overall_cells(scores: Sequence[RunScore]) -> dict[str, str]:
    """The headline measures for one system's runs, in the order the table shows them."""
    answerable = [s for s in scores if s.expected is Outcome.CONCLUSIVE]
    unanswerable = [s for s in scores if s.expected is Outcome.INCONCLUSIVE]
    tool_calls = _mean([s.tool_calls for s in scores], 1)
    attempts = _mean([s.tool_attempts for s in scores], 1)
    return {
        "Correct outcome": _ratio([s.correct for s in scores]),
        "Correct, spread across trials": _spread(scores),
        "Top-1 cause (answerable incidents)": _ratio([s.top1 for s in answerable]),
        "Top-3 cause (answerable incidents)": _ratio([s.top3 for s in answerable]),
        "Wrong conclusion": _ratio([s.wrong_conclusion for s in scores]),
        "Confidently wrong": _ratio([s.confidently_wrong for s in scores]),
        "Abstained on an answerable incident": _ratio([s.abstained for s in answerable]),
        "Inconclusive when it should be": _ratio([s.correct for s in unanswerable]),
        "Citations a tool returned": _percent(
            sum(s.valid_citations for s in scores), sum(s.citations for s in scores)
        ),
        "Key evidence cited for the true cause": _percent(
            sum(s.key_evidence_cited for s in answerable), sum(s.key_evidence for s in answerable)
        ),
        "Citations refused by the board, per run": _mean([s.rejected_citations for s in scores], 1),
        "Decoys cited for the top hypothesis, per run": _mean(
            [s.red_herrings_cited for s in scores], 2
        ),
        "Model calls per run": _mean([s.model_calls for s in scores], 1),
        "Model calls that failed and were retried, per run": _mean(
            [s.model_errors for s in scores], 1
        ),
        "Requests passed to the backup model": str(sum(s.backup_model_calls for s in scores)),
        "Tokens per run": _mean([s.tokens for s in scores]),
        "Tool calls (attempts) per run": f"{tool_calls} ({attempts})",
        "Rounds per run": _mean([s.rounds for s in scores], 1),
        "Wall clock per run, median / p95": _wall(scores),
        "Model time per run": f"{_mean([s.llm_s / 60 for s in scores], 1)} min",
    }


def _tag_cell(scores: Sequence[RunScore], tag: Tag) -> str:
    return _ratio([s.correct for s in scores if tag in s.tags])


def _header(first: str, columns: Sequence[str]) -> str:
    return "\n".join(
        (
            f"| {first} | {' | '.join(columns)} |",
            f"|---|{'---|' * len(columns)}",
        )
    )


def _row(label: str, cells: Sequence[str]) -> str:
    return f"| {label} | {' | '.join(cells)} |"


def _ratio(flags: Sequence[bool | None]) -> str:
    """How many are true, out of those that apply (``None`` means it does not apply)."""
    relevant = [flag for flag in flags if flag is not None]
    if not relevant:
        return "n/a"
    count = sum(relevant)
    return f"{count}/{len(relevant)} ({count / len(relevant):.0%})"


def _percent(part: int, whole: int) -> str:
    return f"{part / whole:.0%}" if whole else "n/a"


def _mean(values: Sequence[float], digits: int = 0) -> str:
    return f"{fmean(values):,.{digits}f}" if values else "n/a"


def _spread(scores: Sequence[RunScore]) -> str:
    trials = sorted({s.trial for s in scores})
    if len(trials) < 2:
        return "n/a (one trial)"
    rates = [fmean(s.correct for s in scores if s.trial == t) for t in trials]
    return f"{min(rates):.0%} to {max(rates):.0%}"


def _percentile(values: Sequence[float], q: float) -> float:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(q * len(ordered)))]


def _wall(scores: Sequence[RunScore]) -> str:
    walls = [s.wall_s for s in scores]
    if not walls:
        return "n/a"
    return f"{median(walls) / 60:.1f} / {_percentile(walls, 0.95) / 60:.1f} min"


def _incident_rows(results: SweepResults, systems: Sequence[System]) -> list[str]:
    incidents = sorted({s.incident_id for s in results.scores})
    rows = []
    for incident_id in incidents:
        cells = []
        for system in systems:
            runs = _runs(results, incident_id, system)
            if not runs:
                cells.append("n/a")
                continue
            correct = sum(s.correct for s in runs)
            outcomes = ", ".join(_outcome_label(s) for s in runs)
            cells.append(f"{correct}/{len(runs)}: {outcomes}")
        rows.append(_row(incident_id, cells))
    return rows


def _outcome_label(score: RunScore) -> str:
    verdict = "right" if score.correct else "wrong"
    if score.outcome is Outcome.INCONCLUSIVE:
        return f"inconclusive ({verdict})"
    return f"concluded ({verdict})"


def _runs(results: SweepResults, incident_id: str, system: System) -> list[RunScore]:
    """One system's runs of one incident, in trial order."""
    runs = [s for s in results.of(system) if s.incident_id == incident_id]
    return sorted(runs, key=lambda s: s.trial)
